// Número do dia no calendário local: vira à meia-noite do aparelho.
function dayNumber(date) {
  return Math.round(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000)
}

// O assunto do dia de um tema. Devolve null para tipos que não são temas diários.
export function dailyTopicOf(type, date = new Date()) {
  const topics = DAILY_TOPICS[type]
  if (!topics) return null
  return topics[dayNumber(date) % topics.length]
}
